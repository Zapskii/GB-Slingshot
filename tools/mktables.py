#!/usr/bin/env python3
"""Generate src/tables.h: launch velocity tables in 8.8 fixed point.

Index = angle * NUM_POWERS + power.
Angles run from ANGLE_MIN degrees in ANGLE_STEP increments.
Speeds are pixels per frame. Positive vx is right, negative vy is up.
"""
import math
import sys

NUM_ANGLES = 16
NUM_POWERS = 8
ANGLE_MIN = 5
ANGLE_STEP = 5
SPEED_MIN = 1.2
SPEED_STEP = 0.25


def fx(v):
    return int(round(v * 256))


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "src/tables.h"
    vx, vy = [], []
    for a in range(NUM_ANGLES):
        rad = math.radians(ANGLE_MIN + a * ANGLE_STEP)
        for p in range(NUM_POWERS):
            speed = SPEED_MIN + p * SPEED_STEP
            vx.append(fx(speed * math.cos(rad)))
            vy.append(-fx(speed * math.sin(rad)))

    def block(name, data):
        lines = []
        for i in range(0, len(data), NUM_POWERS):
            lines.append("    " + ", ".join("%6d" % v for v in data[i:i + NUM_POWERS]))
        return "static const int16_t %s[NUM_ANGLES * NUM_POWERS] = {\n%s\n};\n" % (
            name, ",\n".join(lines))

    with open(out, "w") as f:
        f.write("/* GENERATED by tools/mktables.py - do not edit. */\n")
        f.write("#ifndef TABLES_H\n#define TABLES_H\n\n#include <stdint.h>\n\n")
        f.write("#define NUM_ANGLES %d\n#define NUM_POWERS %d\n" % (NUM_ANGLES, NUM_POWERS))
        f.write("#define ANGLE_MIN_DEG %d\n#define ANGLE_STEP_DEG %d\n\n" % (ANGLE_MIN, ANGLE_STEP))
        f.write("/* 8.8 fixed point, pixels per frame. One row per angle, one column per power. */\n")
        f.write(block("launch_vx", vx))
        f.write("\n")
        f.write(block("launch_vy", vy))
        f.write("\n#endif\n")


if __name__ == "__main__":
    main()
