#!/usr/bin/env python3
"""Generate src/levels.h from the ASCII files in levels/.

Same characters as sim_load_ascii: W wood, S stone, I ice, T target, . empty.
Rows are aligned to the bottom of the grid, so the last row sits on the ground.

An optional "# shots N" line sets that level's shot budget (default 3), and an
optional "# needs A|B|C" line declares the projectile type the level is built
around (default A, the standard shot). test_late_levels_need_a_type checks that
declaration is true by brute force, so it cannot be wishful.

    python3 tools/mklevels.py src
"""
import glob
import sys

W = 20          # GRID_W in sim.h
MAX_ROWS = 16   # playable rows above the two ground rows
DEFAULT_SHOTS = 3
DEFAULT_NEEDS = "A"

# Must match the PT_* enum order in sim.h.
PT = {"A": 0, "B": 1, "C": 2, "D": 3}

# ponytail: no RLE. The plan called for it, but all 10 levels together are a few
# hundred bytes of _CODE out of 32 KB. Add RLE here (and a decoder in main.c) only
# if the level data ever gets big enough to crowd the ROM.

# The slingshot is drawn over columns 2-3 of the bottom four rows; level
# content there would be hidden behind it, so it is refused here.
SLING_COLS = (2, 3)
SLING_ROW = 12


def covers_slingshot(nrows, i):
    """True if row i of an nrows-tall level lands in rows 12-15, where the
    slingshot is drawn."""
    return 16 - nrows + i >= SLING_ROW


def load(path):
    shots = DEFAULT_SHOTS
    needs = DEFAULT_NEEDS
    rows = []
    for line in open(path):
        line = line.rstrip("\n")
        if line.startswith("#"):
            parts = line.lstrip("#").split()
            if len(parts) == 2 and parts[0] == "shots":
                shots = int(parts[1])
            elif len(parts) == 2 and parts[0] == "needs":
                assert parts[1] in PT, "%s: needs %s" % (path, parts[1])
                needs = parts[1]
            continue
        if line.strip():
            rows.append(line)
    assert rows, "%s is empty" % path
    assert len(rows) <= MAX_ROWS, "%s: %d rows, max %d" % (path, len(rows), MAX_ROWS)
    assert 1 <= shots <= 9, "%s: %d shots" % (path, shots)
    for i, r in enumerate(rows):
        assert len(r) == W, "%s row %d is %d chars, want %d" % (path, i + 1, len(r), W)
        assert set(r) <= set(".WSIT"), "%s row %d: unknown char" % (path, i + 1)
        if covers_slingshot(len(rows), i):
            assert r[SLING_COLS[0]:SLING_COLS[1] + 1] == "..", \
                "%s row %d: columns 2-3 are covered by the slingshot" % (path, i + 1)
    assert sum(r.count("T") for r in rows), "%s has no target" % path
    return rows, shots, needs


def main():
    outdir = sys.argv[1] if len(sys.argv) > 1 else "src"
    paths = sorted(glob.glob("levels/*.txt"))
    assert paths, "no levels/*.txt"

    levels = [load(p) for p in paths]

    with open(outdir + "/levels.h", "w") as f:
        f.write("/* GENERATED by tools/mklevels.py - do not edit. */\n")
        f.write("#ifndef LEVELS_H\n#define LEVELS_H\n\n#include <stdint.h>\n\n")
        f.write("#define NUM_LEVELS %d\n\n" % len(levels))
        for i, (rows, _, _) in enumerate(levels):
            f.write("static const char *const level_%d[] = {\n" % i)
            for r in rows:
                f.write('    "%s",\n' % r)
            f.write("};\n")
        f.write("\nstatic const char *const *const level_rows[NUM_LEVELS] = {\n")
        f.write("".join("    level_%d,\n" % i for i in range(len(levels))))
        f.write("};\n")
        f.write("\nstatic const uint8_t level_height[NUM_LEVELS] = { %s };\n"
                % ", ".join(str(len(r)) for r, _, _ in levels))
        f.write("static const uint8_t level_shots[NUM_LEVELS] = { %s };\n"
                % ", ".join(str(s) for _, s, _ in levels))
        f.write("static const uint8_t level_needs[NUM_LEVELS] = { %s };\n"
                % ", ".join(str(PT[n]) for _, _, n in levels))
        f.write("\n#endif\n")

    for p, (rows, shots, needs) in zip(paths, levels):
        print("%s  %d rows, %d shots, %d targets, needs %s"
              % (p, len(rows), shots, sum(r.count("T") for r in rows), needs))


if __name__ == "__main__":
    main()
